"""Generate Unicode tables for the native search from the running Python.

Run once per supported Python version; each interpreter writes the tables of its
own Unicode version to `native/src/unicode_tables/v<major>_<minor>.rs`:

    python3.11 native/tools/generate_unicode.py   # Unicode 14.0
    python3.12 native/tools/generate_unicode.py   # Unicode 15.0
    python3.13 native/tools/generate_unicode.py   # Unicode 15.1
    python3.14 native/tools/generate_unicode.py   # Unicode 16.0

The tables reproduce `str.casefold`, `str.isalnum/isupper/islower` and
`unicodedata.normalize("NFC", ...)` of that version. The test hashes let
`cargo test` prove the Rust implementation matches Python exactly.
"""

from __future__ import annotations

import unicodedata
from pathlib import Path

FNV_OFFSET = 14695981039346656037
FNV_PRIME = 1099511628211
HANGUL_SYLLABLES = range(0xAC00, 0xD7A4)
LCG_MULTIPLIER = 6364136223846793005
LCG_INCREMENT = 1442695040888963407
NFC_SAMPLE_SEED = 20261019
NFC_SAMPLE_COUNT = 60_000
NFC_SAMPLE_MAX_LENGTH = 6


def characters():
    return (chr(code) for code in range(0x110000) if not 0xD800 <= code <= 0xDFFF)


def ranges(predicate):
    result = []
    for char in characters():
        if not predicate(char):
            continue
        code = ord(char)
        if result and result[-1][1] + 1 == code:
            result[-1] = (result[-1][0], code)
        else:
            result.append((code, code))
    return result


def class_ranges():
    """Canonical combining classes as (first, last, class) runs; class 0 is omitted."""
    result = []
    for char in characters():
        value = unicodedata.combining(char)
        if not value:
            continue
        code = ord(char)
        if result and result[-1][1] + 1 == code and result[-1][2] == value:
            result[-1] = (result[-1][0], code, value)
        else:
            result.append((code, code, value))
    return result


def decompositions():
    """Full canonical decompositions; Hangul syllables are computed algorithmically."""
    for char in characters():
        if ord(char) in HANGUL_SYLLABLES:
            continue
        decomposed = unicodedata.normalize("NFD", char)
        if decomposed != char:
            yield ord(char), decomposed


def compositions():
    """Primary composites as (first, second, composite), excluding composition exclusions."""
    result = []
    for char in characters():
        if ord(char) in HANGUL_SYLLABLES:
            continue
        mapping = unicodedata.decomposition(char)
        if not mapping or mapping.startswith("<"):
            continue
        parts = [chr(int(part, 16)) for part in mapping.split()]
        if len(parts) == 2 and unicodedata.normalize("NFC", parts[0] + parts[1]) == char:
            result.append((ord(parts[0]), ord(parts[1]), ord(char)))
    return sorted(result)


def nfc_sample_pool(composition_table):
    """Characters that exercise ordering and composition, in a fixed order."""
    pool = {first for first, _, _ in composition_table}
    pool |= {second for _, second, _ in composition_table}
    pool |= {composite for _, _, composite in composition_table}
    pool |= {ord(char) for char in characters() if unicodedata.combining(char)}
    pool |= set(range(0x1100, 0x1113)) | set(range(0x1161, 0x1176)) | set(range(0x11A8, 0x11C3))
    pool |= {0xAC00, 0xAC01, 0xD7A3, ord("a"), ord("A"), ord("ß"), ord("ǅ")}
    return sorted(pool)


def nfc_samples(pool):
    """Deterministic pseudo-random strings; `unicode.rs` tests rebuild the same ones."""
    state = NFC_SAMPLE_SEED
    for _ in range(NFC_SAMPLE_COUNT):
        state = (state * LCG_MULTIPLIER + LCG_INCREMENT) & 0xFFFFFFFFFFFFFFFF
        length = 1 + (state >> 33) % NFC_SAMPLE_MAX_LENGTH
        chars = []
        for _ in range(length):
            state = (state * LCG_MULTIPLIER + LCG_INCREMENT) & 0xFFFFFFFFFFFFFFFF
            chars.append(chr(pool[(state >> 33) % len(pool)]))
        yield "".join(chars)


def hash_bytes(value, data):
    for byte in data:
        value = ((value ^ byte) * FNV_PRIME) & 0xFFFFFFFFFFFFFFFF
    return value


def rust_string(value):
    return '"' + "".join(f"\\u{{{ord(char):x}}}" for char in value) + '"'


def table_lines(composition_table, pool):
    lines = [
        "// Generated by native/tools/generate_unicode.py; do not edit by hand.",
        f"// Python {unicodedata.unidata_version} casefold, character classes and NFC data.",
        "use crate::unicode::Tables;",
        "",
        "pub static TABLES: Tables = Tables {",
        f'    version: "{unicodedata.unidata_version}",',
        "    casefold: &[",
    ]
    lines += [
        f"        (0x{ord(char):x}, {rust_string(char.casefold())}),"
        for char in characters()
        if char.casefold() != char
    ]
    lines.append("    ],")
    for name, predicate in (("alnum", str.isalnum), ("upper", str.isupper), ("lower", str.islower)):
        lines.append(f"    {name}: &[")
        lines += [f"        (0x{start:x}, 0x{end:x})," for start, end in ranges(predicate)]
        lines.append("    ],")
    lines.append("    combining_classes: &[")
    lines += [f"        (0x{a:x}, 0x{b:x}, {value})," for a, b, value in class_ranges()]
    lines.append("    ],")
    lines.append("    decompositions: &[")
    lines += [f"        (0x{code:x}, {rust_string(text)})," for code, text in decompositions()]
    lines.append("    ],")
    lines.append("    compositions: &[")
    lines += [f"        (0x{a:x}, 0x{b:x}, 0x{c:x})," for a, b, c in composition_table]
    lines.append("    ],")
    lines.append("    nfc_sample_pool: &[")
    lines += [f"        0x{code:x}," for code in pool]
    lines.append("    ],")
    lines.append("};")
    return lines


def test_hashes(pool):
    classes = casefold = nfc = FNV_OFFSET
    for char in characters():
        flags = char.isalnum() | (char.isupper() << 1) | (char.islower() << 2)
        classes = hash_bytes(classes, bytes([flags]))
        casefold = hash_bytes(casefold, char.casefold().encode("utf-8") + b"\0")
        nfc = hash_bytes(nfc, unicodedata.normalize("NFC", char).encode("utf-8") + b"\0")
    for sample in nfc_samples(pool):
        nfc = hash_bytes(nfc, unicodedata.normalize("NFC", sample).encode("utf-8") + b"\0")
    return [
        "",
        "#[cfg(test)]",
        "pub const HASHES: crate::unicode::TestHashes = crate::unicode::TestHashes {",
        f"    classes: {classes},",
        f"    casefold: {casefold},",
        f"    nfc: {nfc},",
        "};",
    ]


def main():
    composition_table = compositions()
    pool = nfc_sample_pool(composition_table)
    major, minor, _ = unicodedata.unidata_version.split(".")
    destination = Path(__file__).resolve().parents[1] / f"src/unicode_tables/v{major}_{minor}.rs"
    lines = table_lines(composition_table, pool) + test_hashes(pool)
    destination.parent.mkdir(exist_ok=True)
    destination.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {destination} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
