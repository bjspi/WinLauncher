"""Regenerate Unicode tables with the reference Python interpreter (Unicode 15)."""

from __future__ import annotations

import unicodedata
from pathlib import Path

UNICODE_VERSION = "15.0.0"
FNV_OFFSET = 14695981039346656037
FNV_PRIME = 1099511628211


def characters():
    return (chr(code) for code in range(0x110000) if not 0xD800 <= code <= 0xDFFF)


def ranges(predicate):
    result = []
    for char in characters():
        code = ord(char)
        if not predicate(char):
            continue
        if result and result[-1][1] + 1 == code:
            result[-1] = (result[-1][0], code)
        else:
            result.append((code, code))
    return result


def rust_string(value):
    return '"' + "".join(f"\\u{{{ord(char):x}}}" for char in value) + '"'


def hash_bytes(value, data):
    for byte in data:
        value = ((value ^ byte) * FNV_PRIME) & 0xFFFFFFFFFFFFFFFF
    return value


def main():
    if unicodedata.unidata_version != UNICODE_VERSION:
        raise RuntimeError(f"Use Python with Unicode {UNICODE_VERSION}")
    lines = [
        "// Generated by native/tools/generate_unicode.py; do not edit by hand.",
        "// Python str.casefold / isalnum / isupper / islower, Unicode 15.0.0.",
        "pub const CASEFOLD: &[(u32, &str)] = &[",
    ]
    for char in characters():
        if char.casefold() != char:
            lines.append(f"    (0x{ord(char):x}, {rust_string(char.casefold())}),")
    lines.append("];")
    for name, predicate in (
        ("ALNUM", str.isalnum),
        ("UPPER", str.isupper),
        ("LOWER", str.islower),
    ):
        lines.append(f"pub const {name}: &[(u32, u32)] = &[")
        lines.extend(f"    (0x{start:x}, 0x{end:x})," for start, end in ranges(predicate))
        lines.append("];")

    classes_hash = fold_hash = FNV_OFFSET
    for char in characters():
        flags = char.isalnum() | (char.isupper() << 1) | (char.islower() << 2)
        classes_hash = hash_bytes(classes_hash, bytes([flags]))
        fold_hash = hash_bytes(fold_hash, char.casefold().encode("utf-8") + b"\0")
    lines.extend(
        (
            "#[cfg(test)]",
            f"pub const CLASSES_HASH: u64 = {classes_hash};",
            "#[cfg(test)]",
            f"pub const CASEFOLD_HASH: u64 = {fold_hash};",
        )
    )
    destination = Path(__file__).resolve().parents[1] / "src/unicode_data.rs"
    destination.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {destination} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
